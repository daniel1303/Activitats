
# Activitat 1.3 - print(), comentaris i indentacio

# Exercici 1: Mostrar el nom, la ciutat i l'edat en línies separades
print("Daniel")  # Mostra el nom
print("Barcelona")  # Mostra la ciutat
print(25)  # Mostra l'edat

# Exercici 2: Mostrar diversos arguments en un sol print
print("Nom:", "Daniel", "Edat:", 25)

# Exercici 3: Separar els arguments amb el símbol |
print("Nom:", "Daniel", "Edat:", 25, sep=" | ")

# Exercici 4: Utilitzar end per evitar el salt de línia
print("Hola", end="---")
print("Daniel")

# Explicació: end evita el salt de línia habitual
# i permet continuar escrivint a la mateixa línia.
